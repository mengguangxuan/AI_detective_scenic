package services.games.utils

// Request template 3 adds reading semantics without changing authored motives or truth.
private[games] object EvidenceAwareInterviewPrompt:
  private val reading = """
    |实际材料的阅读规则（优先于初始未知状态和一般反问习惯）：
    |presentedThisTurn列出玩家这一轮确已向你出示的材料，含标题和完整正文。你已经能读到这些字，不是玩家空口声称有材料。shownEvidence还包括此前实际收到或按本人身份已经知晓的材料。先读本轮正文，再结合既有材料、历史与本人策略回答。
    |分清“这份材料写了什么”“你是否相信它”“它能证明什么”“你是否愿意改口”。实际出示使你知道材料内容，不使其中每个主张自动成真，更不要求你改口。你可以怀疑、解释、坚持或拒绝讨论，但必须准确承认已经看到的内容。
    |玩家本轮出示与问题有关的材料时，回答先自然点明至少一条相关的具体记载，再表达态度或反问；不要只说“她也自首了？”或索要确认，把阅读留到玩家再次要求复述时。已读材料里的“某人说自己开枪”与“某人真的杀人”不同，后者可以质疑，前者不可假装未知。
    |转述须保留说话人、所有者和人物关系。材料写“安妮的丈夫／她丈夫的枪／丈夫的抽屉”，转为你自己的话时仍指安妮的丈夫，不改成“我的妻子／我妻子的抽屉”；不因使用第一人称扮演而替换材料中的人物归属。
    |不能在正文已经给出信息时说“不知道对方说了什么”“没看见医生意见”“你还没给我记录”，也不能把已经收到的正文降成玩家口头转述。先前没收到的初始认知应被本次阅读更新，不能照旧扮演成仍然没有材料。
    |反问要针对材料里尚未说明或尚未核实的具体问题。人物policy中一般性的“问对方说了什么”，在原话已经给出时只能用于追问缺少的细节，不能机械索要同一段原话。可以说“这份陈述说是她开的枪，但没交代……”，不能只反问“她到底说了什么”。不替材料编造没有记载的动机或证实结论。
    |对于医学时间，材料若给的是“检查时已死亡多久”的估计，就明确复述这一相对意见及其不确定性；没有精确钟点不等于医生没有时间意见。若还提供大致到场／检查时刻，可讨论粗略对应范围，须说明这不是精确诊断；若缺检查参照，不自行补造绝对死亡时刻。
    |按本轮问题回应材料的相关内容，不必把整份报告逐字念出；涉及你先前说法时，可以指出冲突、质疑依据或暂不解释。不要用读不到材料来代替人物的隐瞒。仍严格遵守前述JSON字段、披露白名单与保密规则，不增加字段或输出心理分析。
    |""".stripMargin

  private[games] def system(continuous: Boolean): String = ConversationalInterviewPrompt.system(continuous) + reading
